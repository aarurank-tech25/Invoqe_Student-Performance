"""
routers/predictions.py
----------------------
Prediction generation, inference history, and PDF report downloads.
"""

import json
from datetime import datetime, timezone
from typing import List
from fastapi import APIRouter, Depends, HTTPException, status, Response, Request
from fastapi.responses import StreamingResponse
from sqlalchemy.orm import Session

from backend.database import get_db
from backend.models import User, PredictionRecord, AuditLog
from backend.schemas import PredictionInput, PredictionResponse
from backend.auth import get_current_user, get_current_student
from backend.ml_service import predict_student_performance
from backend.report_service import generate_prediction_pdf

router = APIRouter(prefix="/api/predictions", tags=["Predictions"])


@router.post("/predict", response_model=PredictionResponse)
def create_prediction(
    payload: PredictionInput,
    request: Request,
    student: User = Depends(get_current_student),
    db: Session = Depends(get_db)
):
    """
    Generate an AI grade prediction using the saved Scikit-Learn pipeline.
    Saves record to the authenticated student's history.
    """
    input_dict = payload.model_dump()

    try:
        predicted_grade, conf_low, conf_high, category, recommendations = predict_student_performance(input_dict)
    except ValueError as e:
        raise HTTPException(status_code=status.HTTP_400_BAD_REQUEST, detail=str(e))
    except Exception as e:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Inference pipeline execution error: {str(e)}"
        )

    # Persist prediction record
    record = PredictionRecord(
        user_id=student.id,
        predicted_grade=predicted_grade,
        confidence_low=conf_low,
        confidence_high=conf_high,
        performance_category=category,
        model_name="Random Forest Regressor",
        input_features_json=json.dumps(input_dict),
        recommendations_json=json.dumps(recommendations),
        created_at=datetime.now(timezone.utc),
    )
    db.add(record)

    # Audit Log
    audit = AuditLog(
        actor_id=student.id,
        actor_email=student.email,
        action="PREDICTION_CREATED",
        resource_type="PredictionRecord",
        details=f"Generated prediction G3={predicted_grade:.1f} ({category})",
        ip_address=request.client.host if request.client else "127.0.0.1",
    )
    db.add(audit)
    db.commit()
    db.refresh(record)

    return {
        "id": record.id,
        "predicted_grade": record.predicted_grade,
        "confidence_low": record.confidence_low,
        "confidence_high": record.confidence_high,
        "performance_category": record.performance_category,
        "model_name": record.model_name,
        "recommendations": recommendations,
        "input_features": input_dict,
        "created_at": record.created_at,
    }


@router.get("/history", response_model=List[PredictionResponse])
def get_prediction_history(
    student: User = Depends(get_current_student),
    db: Session = Depends(get_db)
):
    """Retrieve all predictions generated by the authenticated student."""
    records = (
        db.query(PredictionRecord)
        .filter(PredictionRecord.user_id == student.id)
        .order_by(PredictionRecord.created_at.desc())
        .all()
    )
    return [
        {
            "id": r.id,
            "predicted_grade": r.predicted_grade,
            "confidence_low": r.confidence_low,
            "confidence_high": r.confidence_high,
            "performance_category": r.performance_category,
            "model_name": r.model_name,
            "recommendations": r.recommendations,
            "input_features": r.input_features,
            "created_at": r.created_at,
        }
        for r in records
    ]


@router.get("/{prediction_id}/pdf")
def download_prediction_pdf(
    prediction_id: int,
    user: User = Depends(get_current_user),
    db: Session = Depends(get_db)
):
    """
    Generate and stream a professional PDF report.
    Enforces strict access control: student can only download their own reports.
    """
    record = db.query(PredictionRecord).filter(PredictionRecord.id == prediction_id).first()
    if not record:
        raise HTTPException(status_code=404, detail="Prediction record not found")

    # Access control: Must be the owner or an admin
    if user.role != "admin" and record.user_id != user.id:
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="Access denied: You cannot download reports belonging to another student.",
        )

    # Owner info
    owner = db.query(User).filter(User.id == record.user_id).first()
    student_name = owner.full_name if owner else "Student"
    student_email = owner.email if owner else "student@aether.edu"

    prediction_dict = {
        "id": record.id,
        "predicted_grade": record.predicted_grade,
        "confidence_low": record.confidence_low,
        "confidence_high": record.confidence_high,
        "performance_category": record.performance_category,
        "model_name": record.model_name,
        "input_features": record.input_features,
        "recommendations": record.recommendations,
        "created_at": record.created_at.strftime("%Y-%m-%d %H:%M UTC"),
    }

    pdf_buffer = generate_prediction_pdf(student_name, student_email, prediction_dict)
    filename = f"AETHER_Evaluation_Report_#{record.id}.pdf"

    return StreamingResponse(
        pdf_buffer,
        media_type="application/pdf",
        headers={"Content-Disposition": f'attachment; filename="{filename}"'},
    )
